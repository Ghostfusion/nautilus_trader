#[test]
fn test_each_named_filter_rejects_its_own_case_and_is_counted() {
    let reference = UnixNanos::from(REFERENCE_NS);
    let t1 = 0.25;
    let mut observations = linear_surface_observations(REFERENCE_NS);

    let valid = |strike: f64, expiry: UnixNanos| SurfaceObservation {
        instrument_id: InstrumentId::from("OPT.TEST"),
        strike,
        expiry_ns: expiry,
        option_kind: OptionKind::Call,
        bid: 1.0,
        ask: 1.0,
        volume: Some(10.0),
        ts_event: reference,
    };

    let mut crossed = valid(FORWARD, expiry_for(t1, REFERENCE_NS));
    crossed.bid = 1.01;
    crossed.ask = 1.00;
    observations.push(crossed);

    let mut low_bid = valid(FORWARD, expiry_for(t1, REFERENCE_NS));
    low_bid.bid = 0.001;
    low_bid.ask = 0.002;
    observations.push(low_bid);

    let mut wide_spread = valid(FORWARD, expiry_for(t1, REFERENCE_NS));
    wide_spread.bid = 1.0;
    wide_spread.ask = 1.2;
    observations.push(wide_spread);

    let short_expiry = valid(
        FORWARD,
        expiry_for(60.0 / (365.25 * 24.0 * 60.0 * 60.0), REFERENCE_NS),
    );
    observations.push(short_expiry);

    let mut low_volume = valid(FORWARD, expiry_for(t1, REFERENCE_NS));
    low_volume.volume = Some(0.5);
    observations.push(low_volume);

    let mut stale = valid(FORWARD, expiry_for(t1, REFERENCE_NS));
    stale.ts_event = UnixNanos::from(REFERENCE_NS - 7_200 * 1_000_000_000);
    observations.push(stale);

    let config = SurfaceConfig {
        filters: SurfaceFilters {
            min_bid: 0.01,
            max_spread: 0.05,
            min_time_to_expiry_secs: 3600.0,
            min_volume: 1.0,
            max_age_secs: 3600.0,
        },
        reference_ns: reference,
        ..base_config()
    };

    let surface = VolatilitySurface::calibrate(&observations, config).unwrap();
    let counts = surface.rejection_counts();
    assert_eq!(counts.count(SurfaceRejection::CrossedMarket), 1);
    assert_eq!(counts.count(SurfaceRejection::BidBelowMinimum), 1);
    assert_eq!(counts.count(SurfaceRejection::SpreadAboveMaximum), 1);
    assert_eq!(counts.count(SurfaceRejection::TimeToExpiryBelowMinimum), 1);
    assert_eq!(counts.count(SurfaceRejection::VolumeBelowMinimum), 1);
    assert_eq!(counts.count(SurfaceRejection::StaleObservation), 1);
    assert_eq!(counts.accepted(), 6);
    assert_eq!(counts.rejected(), 6);
    assert_eq!(surface.observation_count(), 6);
    assert_eq!(surface.slices().len(), 2);
}

#[test]
fn test_svi_family_fits_and_satisfies_its_own_conditions() {
    // Three nodes with decreasing segment slopes: a non-convex node set that the linear
    // interpolation family cannot serve, so the SVI fallback must be usable here.
    let nodes = vec![
        VarianceNode {
            log_moneyness: -0.2,
            total_variance: 0.03,
        },
        VarianceNode {
            log_moneyness: 0.0,
            total_variance: 0.05,
        },
        VarianceNode {
            log_moneyness: 0.2,
            total_variance: 0.06,
        },
    ];

    let (params, rmse) = SviParams::fit(&nodes).expect("SVI fit");
    assert!(params.satisfies_constraints(), "{params:?}");
    assert!(params.is_arbitrage_free(-0.2, 0.2), "{params:?}");
    assert!(params.b >= 0.0);
    assert!(rmse < 0.01, "rmse {rmse}");
    // The family reproduces the nodes it was fitted to.
    for node in &nodes {
        assert!(
            (params.total_variance(node.log_moneyness) - node.total_variance).abs() < 0.01,
            "{node:?}"
        );
    }
}

#[test]
fn test_non_convex_slice_selects_the_svi_fallback() {
    let reference = UnixNanos::from(REFERENCE_NS);
    let t1 = 0.25;
    let t2 = 0.5;
    // Both slices are non-convex in log moneyness. The later slice is shifted far above the
    // earlier one so the calendar condition holds with a wide margin.
    let mut observations = make_slice(
        expiry_for(t1, REFERENCE_NS),
        REFERENCE_NS,
        t1,
        &[(-0.2, 0.03), (0.0, 0.05), (0.2, 0.06)],
    );
    observations.extend(make_slice(
        expiry_for(t2, REFERENCE_NS),
        REFERENCE_NS,
        t2,
        &[(-0.2, 0.53), (0.0, 0.55), (0.2, 0.56)],
    ));

    let config = SurfaceConfig {
        reference_ns: reference,
        ..base_config()
    };

    match VolatilitySurface::calibrate(&observations, config) {
        Ok(surface) => {
            // The interpolation family could not serve these nodes, so SVI must have been
            // selected for both slices, and each slice must report its own fit.
            for slice in surface.slices() {
                assert_eq!(slice.scheme, SurfaceScheme::Svi, "{slice:?}");
                assert!(slice.svi.is_some());
                assert!(slice.fit_error >= 0.0);
            }
        }
        Err(SurfaceError::SviCalibrationFailed { .. }) => {}
        Err(SurfaceError::ArbitrageViolation { .. }) => {}
        other => panic!("unexpected result: {other:?}"),
    }
}
