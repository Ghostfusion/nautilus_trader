//! Tests for the implied volatility surface.
//!
//! No reference values are invented here. Every assertion is an identity: a linear-in-log-
//! moneyness slice reproduces its own nodes, flat extrapolation returns the boundary node, or a
//! counted rejection reason. Observations are generated by pricing the target volatility with the
//! repository's own closed form, so the implied-vol solver round-trips it.

use nautilus_core::UnixNanos;
use nautilus_model::{
    data::{
        greeks::black_scholes_greeks_exact,
        volatility_surface::{
            ArbitrageViolation, ForwardSource, MIN_OBSERVATIONS_PER_SLICE, MIN_SLICES_FOR_CALENDAR,
            SurfaceConfig, SurfaceError, SurfaceFilters, SurfaceObservation, SurfaceRejection,
            SurfaceScheme, SviParams, VarianceNode, VolatilitySurface,
        },
    },
    enums::OptionKind,
    identifiers::InstrumentId,
};

const FORWARD: f64 = 100.0;
const RATE: f64 = 0.0;
const NANOSECONDS_PER_YEAR: f64 = 365.25 * 24.0 * 60.0 * 60.0 * 1_000_000_000.0;
const REFERENCE_NS: u64 = 1_700_000_000_000_000_000;

fn expiry_for(t_years: f64, reference_ns: u64) -> UnixNanos {
    UnixNanos::from(reference_ns + (t_years * NANOSECONDS_PER_YEAR) as u64)
}

/// Prices a call with the repository's own closed form, at cost of carry `b = 0` so the forward
/// equals `FORWARD` and the implied-vol solver must return the input volatility.
fn call_price(strike: f64, vol: f64, t: f64) -> f64 {
    black_scholes_greeks_exact(FORWARD, RATE, 0.0, vol, true, strike, t).price
}

/// Builds one expiry slice of call observations whose total variance matches `nodes`.
fn make_slice(
    expiry_ns: UnixNanos,
    reference_ns: u64,
    t: f64,
    nodes: &[(f64, f64)],
) -> Vec<SurfaceObservation> {
    nodes
        .iter()
        .map(|(log_moneyness, total_variance)| {
            let strike = FORWARD * log_moneyness.exp();
            let vol = (total_variance / t).sqrt();
            let price = call_price(strike, vol, t);
            SurfaceObservation {
                instrument_id: InstrumentId::from("OPT.TEST"),
                strike,
                expiry_ns,
                option_kind: OptionKind::Call,
                bid: price,
                ask: price,
                volume: Some(10.0),
                ts_event: UnixNanos::from(reference_ns),
            }
        })
        .collect()
}

fn base_config() -> SurfaceConfig {
    SurfaceConfig {
        forward_source: ForwardSource::Supplied(FORWARD),
        risk_free_rate: RATE,
        reference_ns: UnixNanos::from(REFERENCE_NS),
        ..SurfaceConfig::default()
    }
}

/// Two linear-in-log-moneyness slices, `w(k) = 0.05 + 0.04 * k` at `T = 0.25` and
/// `w(k) = 0.10 + 0.04 * k` at `T = 0.5`. The second dominates the first at every node, so the
/// calendar condition holds.
fn linear_surface_observations(reference_ns: u64) -> Vec<SurfaceObservation> {
    let t1 = 0.25;
    let t2 = 0.5;
    let mut observations = make_slice(
        expiry_for(t1, reference_ns),
        reference_ns,
        t1,
        &[(-0.2, 0.042), (0.0, 0.05), (0.2, 0.058)],
    );
    observations.extend(make_slice(
        expiry_for(t2, reference_ns),
        reference_ns,
        t2,
        &[(-0.2, 0.092), (0.0, 0.10), (0.2, 0.108)],
    ));
    observations
}

#[test]
fn test_query_inside_fitted_region_interpolates_and_is_not_flagged() {
    let observations = linear_surface_observations(REFERENCE_NS);
    let surface = VolatilitySurface::calibrate(&observations, base_config()).unwrap();

    assert_eq!(surface.slices().len(), 2);
    assert_eq!(
        surface.slices()[0].scheme,
        SurfaceScheme::LinearTotalVariance
    );

    // At the node k = 0 of the first slice the total variance is exactly 0.05.
    let query = surface.query(0.0, 0.25);
    assert!(!query.extrapolated);
    assert!((query.total_variance - 0.05).abs() < 1e-8, "{query:?}");
    assert_eq!(query.observation_count, 3);
    // vol = sqrt(w / T) = sqrt(0.05 / 0.25) = sqrt(0.2).
    assert!((query.implied_volatility - 0.2f64.sqrt()).abs() < 1e-6);

    // Between nodes the linear interpolation returns the line value exactly:
    // w(0.1) = 0.05 + 0.04 * 0.1 = 0.054.
    let between = surface.query(0.1, 0.25);
    assert!(!between.extrapolated);
    assert!((between.total_variance - 0.054).abs() < 1e-8, "{between:?}");
}

#[test]
fn test_query_beyond_moneyness_range_extrapolates_flat_to_boundary() {
    let observations = linear_surface_observations(REFERENCE_NS);
    let surface = VolatilitySurface::calibrate(&observations, base_config()).unwrap();

    let boundary = surface.slices()[0].nodes.last().unwrap().total_variance;
    let query = surface.query(0.5, 0.25);
    assert!(query.extrapolated);
    // Flat extrapolation returns the boundary node value unchanged.
    assert_eq!(query.total_variance, boundary);

    // The destination node carries the line value w(0.2) = 0.058.
    assert!((query.total_variance - 0.058).abs() < 1e-8);
}

#[test]
fn test_query_beyond_expiry_range_extrapolates_flat() {
    let observations = linear_surface_observations(REFERENCE_NS);
    let surface = VolatilitySurface::calibrate(&observations, base_config()).unwrap();

    let inside = surface.query(0.0, 0.5);
    let beyond = surface.query(0.0, 1.0);
    assert!(!inside.extrapolated);
    assert!(beyond.extrapolated);
    // Flat in time: the last slice's value is returned unchanged.
    assert_eq!(beyond.total_variance, inside.total_variance);
}

#[test]
fn test_calendar_violation_is_rejected() {
    let t1 = 0.25;
    let t2 = 0.5;
    // The later slice has a strictly smaller total variance than the earlier one at every node,
    // so it violates the calendar condition. Both slices are individually convex.
    let mut observations = make_slice(
        expiry_for(t1, REFERENCE_NS),
        REFERENCE_NS,
        t1,
        &[(-0.2, 0.08), (0.0, 0.088), (0.2, 0.096)],
    );
    observations.extend(make_slice(
        expiry_for(t2, REFERENCE_NS),
        REFERENCE_NS,
        t2,
        &[(-0.2, 0.05), (0.0, 0.058), (0.2, 0.066)],
    ));

    let result = VolatilitySurface::calibrate(&observations, base_config());
    assert!(
        matches!(
            result,
            Err(SurfaceError::ArbitrageViolation {
                violation: ArbitrageViolation::Calendar { .. }
            })
        ),
        "{result:?}"
    );
}

#[test]
fn test_too_few_observations_refuses_a_slice() {
    let t = 0.25;
    let mut observations = make_slice(
        expiry_for(t, REFERENCE_NS),
        REFERENCE_NS,
        t,
        &[(-0.2, 0.042), (0.0, 0.05)],
    );
    observations.extend(make_slice(
        expiry_for(0.5, REFERENCE_NS),
        REFERENCE_NS,
        0.5,
        &[(-0.2, 0.092), (0.0, 0.10)],
    ));

    let result = VolatilitySurface::calibrate(&observations, base_config());
    assert!(
        matches!(
            result,
            Err(SurfaceError::TooFewObservations {
                found,
                required: MIN_OBSERVATIONS_PER_SLICE,
                ..
            }) if found < MIN_OBSERVATIONS_PER_SLICE
        ),
        "{result:?}"
    );
}

#[test]
fn test_declared_minimums() {
    // Three points are the minimum that can carry a convexity statement, and two slices the
    // minimum that can carry a calendar statement.
    assert_eq!(MIN_OBSERVATIONS_PER_SLICE, 3);
    assert_eq!(MIN_SLICES_FOR_CALENDAR, 2);
}

